// Helper to get formatted relative dates
const getTodayStr = () => {
  const d = new Date();
  return d.toISOString().split('T')[0];
};

const getRelativeDateStr = (offsetDays: number) => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

